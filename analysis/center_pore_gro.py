#!/usr/bin/env python3
"""Recentre a pore snapshot on its chain-coordinate cylinder, across PBC.

The CV cylinder's in-plane position is frozen wherever the pore was created, so
nothing guarantees it sits mid-box.  When it lands within ~1 nm of a box face
(the rebuilt DMPG runs put the CHARMM pore 0.43 nm and the AMBER pore 0.25 nm
from one), half of the pore's surroundings live on the *other* side of the
periodic box: PyMOL auto-zooms onto the cylinder and renders a pore with
membrane on one side and empty canvas on the other.  The physics is fine, the
picture is not.

This shifts the whole system in x/y so the cylinder axis is mid-box and wraps
**whole molecules** back in (wrapping per atom would tear lipids and waters
apart at the seam), then writes:

    snapshots/{stem}_centred.gro        the shifted structure
    snapshots/{stem%_last_conf}_cyl_centred.pml   the matching `cyl` line

`render_snapshots.py` prefers both when present, so the committed
``*_cyl_style.pml`` stays the untouched record of the run's real geometry.

Molecules are found by *bonds*, guessed geometrically -- the raw Lipid21 gros
number every residue 1, so residue-based wrapping would move the whole lipid
block as one unit and wrap nothing.

Needs MDAnalysis:
    conda run -n lipid64 python analysis/center_pore_gro.py snapshots/charmm_DMPG_last_conf.gro
    conda run -n lipid64 python analysis/center_pore_gro.py            # every *_last_conf.gro with a cyl pml
"""

import argparse
import re
import sys
from pathlib import Path

import numpy as np
import MDAnalysis as mda

ROOT = Path(__file__).resolve().parent.parent
SNAP = ROOT / "snapshots"

CYL_RE = re.compile(r"^cyl\s+([-\d.]+),([-\d.]+),([-\d.]+),([-\d.]+)")


def read_cyl(pml):
    """(cx, cy, z1, z2) in nm from a cyl_style.pml, or None."""
    for line in pml.read_text().splitlines():
        m = CYL_RE.match(line.strip())
        if m:
            return tuple(float(v) for v in m.groups())
    return None


def centre(gro, verbose=True):
    stem = gro.stem                              # {ff}_{lipid}_last_conf
    base = stem.rsplit("_last_conf", 1)[0]       # {ff}_{lipid}
    pml = SNAP / f"{base}_cyl_style.pml"
    if not pml.exists():
        print(f"  skip {gro.name}: no {pml.name} to read the cylinder from")
        return None
    cyl = read_cyl(pml)
    if cyl is None:
        print(f"  skip {gro.name}: no cyl line in {pml.name}")
        return None
    cx, cy, z1, z2 = cyl

    u = mda.Universe(str(gro))
    box = u.dimensions[:3]                       # A
    shift = np.array([box[0] / 2 - cx * 10, box[1] / 2 - cy * 10, 0.0])
    if verbose:
        edge = min(cx * 10, box[0] - cx * 10, cy * 10, box[1] - cy * 10) / 10
        print(f"  {gro.name}: pore ({cx:.2f}, {cy:.2f}) nm, {edge:.2f} nm from "
              f"the nearest face -> shifting by "
              f"({shift[0] / 10:+.2f}, {shift[1] / 10:+.2f}) nm")

    u.atoms.translate(shift)
    # Whole-molecule wrap: bonds are guessed because a raw Lipid21 gro numbers
    # every residue 1, which would make "residues" useless here.
    u.atoms.guess_bonds()
    u.atoms.wrap(compound="fragments", inplace=True)

    out_gro = SNAP / f"{stem}_centred.gro"
    u.atoms.write(str(out_gro))
    out_pml = SNAP / f"{base}_cyl_centred.pml"
    out_pml.write_text(
        "# generated by analysis/center_pore_gro.py -- do not edit\n"
        f"# {base}: pore recentred from ({cx:.5f}, {cy:.5f}) nm\n"
        f"cyl {box[0] / 20:.5f},{box[1] / 20:.5f},{z1:.5f},{z2:.5f},u=nm\n")
    print(f"    wrote {out_gro.name} + {out_pml.name}")
    return out_gro


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("gro", nargs="*", type=Path,
                    help="pore .gro files (default: every snapshots/"
                         "*_last_conf.gro that has a cyl_style.pml)")
    args = ap.parse_args()
    gros = args.gro or sorted(SNAP.glob("*_last_conf.gro"))
    if not gros:
        sys.exit("no *_last_conf.gro found")
    for gro in gros:
        centre(gro)


if __name__ == "__main__":
    main()
