#!/usr/bin/env python3
"""Render the two large AMBER NPAT HMMM final configurations at an oblique angle.

``traj/big_hmmm_{stable,broken}.gro`` are the last frames of two large HMMM
runs (904 lipids, ~19.6 x 17.0 x 8.1 nm hexagonal box, AMBER, NPAT): one stayed
a bilayer, the other broke up.  This renders both for ``figSI_big_hmmm.py`` in
the usual HMMM style from ``render_snapshots`` -- tail carbons ``gray30``,
headgroup carbons ``gray80``, phosphorus ``orange``, DCLE as pale-green sticks,
hydrogens off.

Camera
------
Unlike the edge-on small-system panels, these are viewed **from 45 deg above
the membrane plane, facing an edge of the box**: from the top-down view the
box is tilted 45 deg about the screen x axis (``turn x, -45``) and nothing
else, so the box's ``a`` edge runs across the front of the frame.  The view is
orthoscopic and framed on the **box** (the eight corners of the rectangular
brick that ``trjconv -ur rect`` wraps into, padded by ``MARGIN``) rather than on the atoms, so both panels have exactly the same
scale and a broken membrane cannot change the framing.  The image aspect
follows from the projected box, and the camera is placed by arithmetic
(orthoscopic visible height = ``2 dist tan(fov/2)``) instead of ``zoom``, which
letterboxes against the headless viewport.

The ``.gro`` files are rendered as downloaded: they were made with
``gmx trjconv -pbc mol`` on the cluster, so every molecule is already whole.

    python3 HMMM/analysis/render_big_hmmm.py
    ... --which stable  --px 600     # quick look

Output: ``HMMM/plots/snapshots/big_hmmm_{stable,broken}.png`` (+ ``_render.pml``).
"""

import argparse
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent                       # HMMM/
sys.path.insert(0, str(HERE))

import render_snapshots as rs                                   # noqa: E402

TRAJ = ROOT / "traj"
OUT = ROOT / "plots" / "snapshots"
SYSTEMS = ["stable", "broken"]

PANEL_MM = 88.0          # two panels side by side in a 180 mm figure
DPI = 600
ELEVATION = 45.0         # deg above the membrane plane
MARGIN = 15.0            # A around the box: -pbc mol keeps molecules whole
                         # with their centre in the box, so atoms poke past a face


def stem(which):
    return "big_hmmm_%s" % which


# ------------------------------------------------------------------ camera
def box_vectors(gro):
    """Box vectors (rows, A) from a .gro's last line -- stdlib + numpy."""
    import numpy as np
    v = [10.0 * float(x) for x in gro.read_text().splitlines()[-1].split()]
    v += [0.0] * (9 - len(v))
    # .gro order: v1x v2y v3z v1y v1z v2x v2z v3x v3y
    return np.array([[v[0], v[3], v[4]],
                     [v[5], v[1], v[6]],
                     [v[7], v[8], v[2]]])


def build_pml(which, png, px, bg="transparent"):
    gro = TRAJ / (stem(which) + ".gro")
    M = box_vectors(gro)
    dcle, lipids, tail, head = rs.selections("amber")
    # Frame the rectangular brick, not the triclinic cell: trjconv -pbc mol
    # (default -ur rect) puts every molecule's centre in [0, a_x) x [0, b_y) x
    # [0, c_z), whereas the hexagonal cell's slanted b vector would add ~10 nm
    # of empty width.
    lx, ly, lz = M[0, 0], M[1, 1], M[2, 2]
    verts = [[i * lx, j * ly, l * lz]
             for i in (0, 1) for j in (0, 1) for l in (0, 1)]
    L = ["# generated by HMMM/analysis/render_big_hmmm.py -- do not edit",
         "load %s, sys" % gro,
         "hide everything",
         "show spheres, %s" % lipids,
         "color %s, %s" % (rs.LIPID_COLOUR, lipids),
         "color %s, %s" % (rs.TAIL_COLOUR, tail),
         "color %s, %s" % (rs.HEAD_COLOUR, head),
         "color %s, (%s) and name P*" % (rs.PHOSPHORUS_COLOUR, lipids),
         "show sticks, %s" % dcle,
         "color %s, %s" % (rs.DCLE_COLOUR, dcle),
         "hide everything, hydro",
         "",
         "# Edge-on to the box, %.0f deg above the membrane plane (see module"
         % ELEVATION,
         "# docstring).",
         "set orthoscopic, 1",
         "turn x, %.3f" % -ELEVATION]
    if bg == "transparent":
        L.append("set ray_opaque_background, 0")
    else:
        L += ["bg_color %s" % bg, "set ray_opaque_background, 1"]
    L += [
        "python",
        "from pymol import cmd",
        "import math",
        "import numpy as np",
        "v = list(cmd.get_view())",
        "R = np.array(v[:9]).reshape(3, 3).T     # model -> camera (column-major)",
        "verts = np.array(%r)" % verts,
        "cam = verts @ R.T",
        "lo, hi = cam.min(0) - %.1f, cam.max(0) + %.1f" % (MARGIN, MARGIN),
        "w, h = hi[0] - lo[0], hi[1] - lo[1]",
        "centre = R.T @ (0.5 * (lo + hi))        # back to model space",
        "fov = cmd.get_setting_float('field_of_view')",
        "dist = 0.5 * h / math.tan(math.radians(0.5 * fov))",
        "span = float(np.ptp(cam[:, 2])) + 2 * %.1f" % MARGIN,
        "v[9], v[10], v[11] = 0.0, 0.0, -dist",
        "v[12], v[13], v[14] = (float(c) for c in centre)",
        "v[15], v[16] = max(1.0, dist - span), dist + span",
        "cmd.set_view(v)",
        "px = %d" % px,
        "cmd.png(%r, width=px, height=int(round(px * h / w)), dpi=%d, ray=1)"
        % (str(png), DPI),
        "python end",
        "quit"]
    return "\n".join(L) + "\n"


def main():
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--which", nargs="*", default=SYSTEMS, choices=SYSTEMS)
    ap.add_argument("--px", type=int, default=int(round(PANEL_MM / 25.4 * DPI)),
                    help="image width in pixels (default: %.0f mm at %d dpi)"
                         % (PANEL_MM, DPI))
    ap.add_argument("--bg", default="transparent")
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()
    pymol = rs.find_pymol()
    OUT.mkdir(parents=True, exist_ok=True)
    for which in args.which:
        png = OUT / (stem(which) + ".png")
        pml = OUT / (stem(which) + "_render.pml")
        pml.write_text(build_pml(which, png, args.px, args.bg))
        if args.dry_run:
            print("wrote %s" % pml)
            continue
        print("rendering %s ..." % stem(which), flush=True)
        subprocess.run([pymol, "-cq", str(pml)], check=True)
        print("wrote %s" % png)


if __name__ == "__main__":
    main()
